-- Cuentas de acceso. El rol define los permisos (admin = coordinador, docente).
CREATE TABLE usuarios (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL,
    email          VARCHAR(150) NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    rol            VARCHAR(20)  NOT NULL DEFAULT 'docente',
    creado_en      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_usuarios_email   UNIQUE (email),
    CONSTRAINT ck_usuarios_email   CHECK (email = lower(email)),
    CONSTRAINT ck_usuarios_rol     CHECK (rol IN ('admin', 'docente'))
);

-- Catálogo de instituciones educativas (evita repetir el nombre en cada matrícula).
CREATE TABLE instituciones (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre     VARCHAR(150) NOT NULL,
    creado_en  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_instituciones_nombre UNIQUE (nombre)
);

-- Estudiantes monitoreados. El promedio y la lectura NO se guardan aquí:
-- se derivan del historial (rendimientos) mediante la vista v_estudiantes_indicadores.
CREATE TABLE estudiantes (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(120)  NOT NULL,
    documento       VARCHAR(20),
    grado           VARCHAR(20)   NOT NULL,
    asistencia      NUMERIC(5,2),
    creado_por      INTEGER REFERENCES usuarios (id) ON DELETE SET NULL,
    creado_en       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    actualizado_en  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_estudiantes_documento UNIQUE (documento),
    CONSTRAINT ck_estudiantes_nombre     CHECK (length(btrim(nombre)) >= 2),
    CONSTRAINT ck_estudiantes_asistencia CHECK (asistencia IS NULL OR asistencia BETWEEN 0 AND 100)
);

-- Registro de matrícula (DFD 1). Indicadores del Banco Mundial a los que aporta.
CREATE TABLE matriculas (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id    INTEGER      NOT NULL REFERENCES estudiantes (id) ON DELETE CASCADE,
    institucion_id   INTEGER      NOT NULL REFERENCES instituciones (id),
    grado            VARCHAR(20)  NOT NULL,
    fecha_matricula  DATE,
    ind_prm          BOOLEAN      NOT NULL DEFAULT TRUE,   -- SE.PRM.ENRR  (matrícula primaria)
    ind_lit          BOOLEAN      NOT NULL DEFAULT TRUE,   -- SE.ADT.LITR.ZS (alfabetización)
    registrado_por   INTEGER REFERENCES usuarios (id) ON DELETE SET NULL,
    creado_en        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Historial académico por período (DFD 2 / D2).
CREATE TABLE rendimientos (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id   INTEGER      NOT NULL REFERENCES estudiantes (id) ON DELETE CASCADE,
    periodo         VARCHAR(40)  NOT NULL,
    matematicas     NUMERIC(2,1),
    lenguaje        NUMERIC(2,1),
    lectura         NUMERIC(5,2),
    observaciones   VARCHAR(500),
    registrado_por  INTEGER REFERENCES usuarios (id) ON DELETE SET NULL,
    creado_en       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_rend_matematicas CHECK (matematicas IS NULL OR matematicas BETWEEN 0 AND 5),
    CONSTRAINT ck_rend_lenguaje    CHECK (lenguaje    IS NULL OR lenguaje    BETWEEN 0 AND 5),
    CONSTRAINT ck_rend_lectura     CHECK (lectura     IS NULL OR lectura     BETWEEN 0 AND 100),
    CONSTRAINT ck_rend_algun_dato  CHECK (matematicas IS NOT NULL OR lenguaje IS NOT NULL OR lectura IS NOT NULL)
);

-- Alertas manuales: casos excepcionales que el sistema no detecta solo (DFD 3).
-- Las alertas automáticas NO se guardan: se calculan a partir del riesgo.
CREATE TABLE alertas_manuales (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_nombre  VARCHAR(120) NOT NULL,
    grado              VARCHAR(20)  NOT NULL,
    nivel              VARCHAR(10)  NOT NULL,
    motivo             VARCHAR(300) NOT NULL,
    recomendacion      VARCHAR(300),
    registrado_por     INTEGER REFERENCES usuarios (id) ON DELETE SET NULL,
    creado_en          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_alertas_nivel CHECK (nivel IN ('alto', 'medio'))
);

-- Historial de reportes descargados (DFD 4).
CREATE TABLE reportes_descargas (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_archivo  VARCHAR(120) NOT NULL,
    usuario_id      INTEGER REFERENCES usuarios (id) ON DELETE SET NULL,
    creado_en       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_matriculas_estudiante   ON matriculas (estudiante_id);
CREATE INDEX idx_matriculas_institucion  ON matriculas (institucion_id);
CREATE INDEX idx_rendimientos_estudiante ON rendimientos (estudiante_id, id DESC);

-- Estudiante + indicadores vigentes:
--   promedio = promedio de matemáticas y lenguaje del último registro que tenga alguna nota
--   lectura  = último nivel de lectura registrado
CREATE VIEW v_estudiantes_indicadores AS
SELECT e.id,
       e.nombre,
       e.documento,
       e.grado,
       e.asistencia,
       p.promedio,
       l.lectura,
       e.creado_en,
       e.actualizado_en
FROM estudiantes e
LEFT JOIN LATERAL (
    SELECT ROUND(((COALESCE(r.matematicas, 0) + COALESCE(r.lenguaje, 0))
                  / ((r.matematicas IS NOT NULL)::int + (r.lenguaje IS NOT NULL)::int))::numeric, 1) AS promedio
    FROM rendimientos r
    WHERE r.estudiante_id = e.id
      AND (r.matematicas IS NOT NULL OR r.lenguaje IS NOT NULL)
    ORDER BY r.id DESC
    LIMIT 1
) p ON TRUE
LEFT JOIN LATERAL (
    SELECT r.lectura
    FROM rendimientos r
    WHERE r.estudiante_id = e.id AND r.lectura IS NOT NULL
    ORDER BY r.id DESC
    LIMIT 1
) l ON TRUE;

